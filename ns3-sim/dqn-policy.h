#ifndef DQN_POLICY_H
#define DQN_POLICY_H

#include <algorithm>
#include <array>
#include <cmath>
#include <fstream>
#include <iostream>
#include <sstream>
#include <stdexcept>
#include <string>
#include <vector>

// ─────────────────────────────────────────────────────────────────────────
// Frozen schema and normalization constants (must match state_spec.py)
// ─────────────────────────────────────────────────────────────────────────
static const std::string STATE_SCHEMA_HASH = "7c486950";
static const float DELTA_MAX = 10.0f;
static const float W_MAX = 10.0f;
static const float RSSI_MIN = -100.0f;
static const float RSSI_RANGE = 70.0f;

static const size_t OBS_DIM = 16;
static const size_t ACTION_DIM = 4;

/**
 * Header-only C++ MLP policy for NS-3 / C++ standalone inference (N1.2).
 * Zero external dependencies (no ns-3, no Torch, no ONNX).
 * Executes 16 -> 64 -> 64 -> 4 forward pass with schema hash validation.
 */
class DqnPolicy
{
  public:
    struct Layer
    {
        int layer_idx{0};
        int out_features{0};
        int in_features{0};
        std::vector<float> weights; // row-major [out_features * in_features]
        std::vector<float> biases;  // [out_features]
    };

    DqnPolicy() = default;

    /**
     * Loads plain-text exported weights generated by deploy/export_ns3.py.
     * Throws std::runtime_error on I/O error or schema hash mismatch.
     */
    bool Load(const std::string& path)
    {
        std::ifstream file(path);
        if (!file.is_open())
        {
            throw std::runtime_error("DqnPolicy::Load: cannot open file: " + path);
        }

        std::string magic;
        int version = 0;
        if (!(file >> magic >> version) || magic != "AOIDQN" || version != 1)
        {
            throw std::runtime_error("DqnPolicy::Load: invalid header format in: " + path);
        }

        std::string hash_label, hash_val;
        if (!(file >> hash_label >> hash_val) || hash_label != "schema_hash")
        {
            throw std::runtime_error("DqnPolicy::Load: missing schema_hash in: " + path);
        }

        if (hash_val != STATE_SCHEMA_HASH)
        {
            throw std::runtime_error("DqnPolicy::Load: schema_hash mismatch! File has '" + hash_val +
                                     "', expected '" + STATE_SCHEMA_HASH + "'");
        }
        m_schemaHash = hash_val;

        std::string layers_label;
        int n_layers = 0;
        if (!(file >> layers_label >> n_layers) || layers_label != "n_layers" || n_layers <= 0)
        {
            throw std::runtime_error("DqnPolicy::Load: invalid n_layers in: " + path);
        }

        m_layers.clear();
        m_layers.reserve(n_layers);

        for (int l = 0; l < n_layers; ++l)
        {
            Layer layer;
            std::string layer_token;
            if (!(file >> layer_token >> layer.layer_idx >> layer.out_features >> layer.in_features) ||
                layer_token != "layer")
            {
                throw std::runtime_error("DqnPolicy::Load: error parsing layer header at index " +
                                         std::to_string(l));
            }

            size_t w_count = static_cast<size_t>(layer.out_features) * layer.in_features;
            layer.weights.resize(w_count);
            for (size_t w = 0; w < w_count; ++w)
            {
                if (!(file >> layer.weights[w]))
                {
                    throw std::runtime_error("DqnPolicy::Load: unexpected EOF reading weights at layer " +
                                             std::to_string(l));
                }
            }

            layer.biases.resize(layer.out_features);
            for (int b = 0; b < layer.out_features; ++b)
            {
                if (!(file >> layer.biases[b]))
                {
                    throw std::runtime_error("DqnPolicy::Load: unexpected EOF reading biases at layer " +
                                             std::to_string(l));
                }
            }

            m_layers.push_back(std::move(layer));
        }

        m_isLoaded = true;
        return true;
    }

    bool IsLoaded() const
    {
        return m_isLoaded;
    }

    const std::string& GetSchemaHash() const
    {
        return m_schemaHash;
    }

    /**
     * Forward pass computing Q-values for all actions given a 16-D normalized observation.
     */
    std::array<float, ACTION_DIM> Forward(const float obs[OBS_DIM]) const
    {
        if (!m_isLoaded)
        {
            throw std::runtime_error("DqnPolicy::Forward called before Load()");
        }

        std::vector<float> cur(obs, obs + OBS_DIM);

        for (size_t l = 0; l < m_layers.size(); ++l)
        {
            const auto& layer = m_layers[l];
            std::vector<float> nxt(layer.out_features);

            for (int o = 0; o < layer.out_features; ++o)
            {
                double sum = layer.biases[o];
                const float* w_row = &layer.weights[o * layer.in_features];
                for (int i = 0; i < layer.in_features; ++i)
                {
                    sum += static_cast<double>(cur[i]) * static_cast<double>(w_row[i]);
                }

                float val = static_cast<float>(sum);
                // ReLU on all hidden layers; final layer is linear
                if (l + 1 < m_layers.size())
                {
                    val = std::max(0.0f, val);
                }
                nxt[o] = val;
            }
            cur = std::move(nxt);
        }

        if (cur.size() != ACTION_DIM)
        {
            throw std::runtime_error("DqnPolicy::Forward output dimension != ACTION_DIM");
        }

        std::array<float, ACTION_DIM> q;
        for (size_t a = 0; a < ACTION_DIM; ++a)
        {
            q[a] = cur[a];
        }
        return q;
    }

    /**
     * Greedy action selection with first-max tie-breaking (identical to np.argmax).
     */
    int Act(const float obs[OBS_DIM]) const
    {
        auto q = Forward(obs);
        int best_action = 0;
        float max_q = q[0];
        for (size_t a = 1; a < ACTION_DIM; ++a)
        {
            if (q[a] > max_q)
            {
                max_q = q[a];
                best_action = static_cast<int>(a);
            }
        }
        return best_action;
    }

    /**
     * Masked greedy action selection: ignores actions where mask[a] == false.
     * If all actions are masked out, falls back to action 0.
     */
    int ActMasked(const float obs[OBS_DIM], const std::vector<bool>& mask) const
    {
        auto q = Forward(obs);
        int best_action = -1;
        float max_q = -1e30f;

        for (size_t a = 0; a < ACTION_DIM; ++a)
        {
            if (a < mask.size() && !mask[a])
            {
                continue; // node unreachable or masked
            }
            if (best_action == -1 || q[a] > max_q)
            {
                max_q = q[a];
                best_action = static_cast<int>(a);
            }
        }

        return (best_action >= 0) ? best_action : 0;
    }

  private:
    bool m_isLoaded{false};
    std::string m_schemaHash;
    std::vector<Layer> m_layers;
};

#endif // DQN_POLICY_H
